const DICTS = { en: EN, bn: BN };

// Translate a key. Unknown language or missing key falls back to English;
// unknown keys return the key itself (never crash the render).
export function t(lang, key, vars) {
  const dict = DICTS[lang] || EN;
  let s = dict[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

// Keys present in English but missing in Bengali (must be empty).
export function missingBnKeys() {
  return Object.keys(EN).filter((k) => !(k in BN));
}
