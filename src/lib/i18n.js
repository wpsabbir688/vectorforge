export const LANGUAGES = ['en', 'bn'];

export function getInitialLanguage() {
  try {
    const v = localStorage.getItem('vectorforge-language');
    if (v === 'bn' || v === 'en') return v;
  } catch { /* private mode */ }
  return 'en';
}

